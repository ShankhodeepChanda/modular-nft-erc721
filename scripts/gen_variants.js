// Generates the 2x2x2x2 factorial ablation contracts into variants/.
// Factors: metadata (shared base URI | per-token URI storage), reentrancy guard, pausable mint, supply cap.
const fs = require('fs'), path = require('path');
const out = path.join(__dirname, '..', 'variants');
const names = [];
for (const uri of ['base', 'token']) for (const g of [0, 1]) for (const p of [0, 1]) for (const c of [0, 1]) {
  const n = `V_${uri}_G${g}P${p}C${c}`; names.push(n);
  const T = uri === 'token';
  const bases = ['ERC721', ...(T ? ['ERC721URIStorage'] : []), 'Ownable', ...(p ? ['Pausable'] : []), ...(g ? ['ReentrancyGuard'] : [])];
  const mods = `onlyOwner${p ? ' whenNotPaused' : ''}${g ? ' nonReentrant' : ''}`;
  const src = `// SPDX-License-Identifier: MIT
// GENERATED by scripts/gen_variants.js - do not edit. Ablation variant: metadata=${uri}, guard=${g}, pause=${p}, cap=${c}.
pragma solidity ^0.8.20;
import {ERC721} from "@openzeppelin/contracts/token/ERC721/ERC721.sol";
import {ERC721URIStorage} from "@openzeppelin/contracts/token/ERC721/extensions/ERC721URIStorage.sol";
import {Ownable} from "@openzeppelin/contracts/access/Ownable.sol";
import {Pausable} from "@openzeppelin/contracts/utils/Pausable.sol";
import {ReentrancyGuard} from "@openzeppelin/contracts/utils/ReentrancyGuard.sol";

contract ${n} is ${bases.join(', ')} {
    error MaxSupplyReached();
    error ZeroQuantity();
${c ? '    uint256 public immutable MAX_SUPPLY;\n' : ''}    uint256 private _nextId;
${T ? '' : '    string private _baseTokenURI;\n'}
    constructor(string memory name_, string memory symbol_, string memory ${T ? '' : 'baseURI_'}, uint256 ${c ? 'maxSupply_' : ''}, address owner_)
        ERC721(name_, symbol_) Ownable(owner_) {
${T ? '' : '        _baseTokenURI = baseURI_;\n'}${c ? '        MAX_SUPPLY = maxSupply_;\n' : ''}    }
${T ? `
    function tokenURI(uint256 id) public view override(ERC721, ERC721URIStorage) returns (string memory) { return super.tokenURI(id); }
    function supportsInterface(bytes4 i) public view override(ERC721, ERC721URIStorage) returns (bool) { return super.supportsInterface(i); }

    function mint(address to, string calldata uri) external ${mods} returns (uint256 id) {
        id = _nextId;
${c ? '        if (id >= MAX_SUPPLY) revert MaxSupplyReached();\n' : ''}        unchecked { _nextId = id + 1; }
        _safeMint(to, id);
        _setTokenURI(id, uri);
    }
` : `
    function _baseURI() internal view override returns (string memory) { return _baseTokenURI; }

    function mint(address to) external ${mods} returns (uint256 id) {
        id = _nextId;
${c ? '        if (id >= MAX_SUPPLY) revert MaxSupplyReached();\n' : ''}        unchecked { _nextId = id + 1; }
        _safeMint(to, id);
    }

    function mintBatch(address to, uint256 qty) external ${mods} {
        if (qty == 0) revert ZeroQuantity();
        uint256 start = _nextId;
${c ? '        if (start + qty > MAX_SUPPLY) revert MaxSupplyReached();\n' : ''}        unchecked { _nextId = start + qty; }
        for (uint256 i; i < qty; ) { _safeMint(to, start + i); unchecked { ++i; } }
    }
`}${p ? '    function pause() external onlyOwner { _pause(); }\n    function unpause() external onlyOwner { _unpause(); }\n' : ''}}
`;
  fs.writeFileSync(path.join(out, n + '.sol'), src);
}
fs.writeFileSync(path.join(out, 'Looper.sol'), `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.20;
/// Owner-proxy used for the "ten sequential single mints inside ONE transaction" workload.
contract Looper {
    function run(address target, address to, uint256 n) external {
        for (uint256 i; i < n; ) {
            (bool ok, bytes memory r) = target.call(abi.encodeWithSignature("mint(address)", to));
            if (!ok) { assembly { revert(add(r, 32), mload(r)) } }
            unchecked { ++i; }
        }
    }
}
`);
fs.writeFileSync(path.join(out, 'variants.json'), JSON.stringify(names));
console.log(names.length + ' variants generated');
